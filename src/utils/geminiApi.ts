/**
 * Turns uploaded file or study notes into structured ALE review quiz using Gemini API
 */
export async function generateQuizWithGemini({
  apiKey,
  notesText,
  fileItem,
  topicTitle = 'Architecture Review',
  model,
}: {
  apiKey: string;
  notesText?: string;
  fileItem?: UploadedFileItem;
  topicTitle?: string;
  model?: string;
}): Promise<{ questions: QuizQuestion[]; flashcards: FlashcardItem[] }> {
  const chosenModel = model || getStoredGeminiModel();

  const prompt = `You are an expert reviewer for the Philippine Architecture Licensure Examination (ALE / PRC Board Exam).
Analyze the provided study material and generate a 6-item multiple-choice exam and 4 flashcards.

Format your response strictly as valid JSON with no markdown wrapping or backticks:
{
  "questions": [
    {
      "id": "q-1",
      "type": "multiple-choice",
      "question": "Question text here?",
      "options": ["Option A", "Option B", "Option C", "Option D"],
      "correctAnswer": 0,
      "explanation": "Detailed explanation citing the specific Philippine code or architectural theory.",
      "codeReference": "e.g. PD 1096 Section 805 or BP 344 Rule II",
      "category": "${topicTitle}"
    }
  ],
  "flashcards": [
    {
      "id": "fc-1",
      "front": "Term or Concept",
      "back": "Exact rule, dimension, or definition",
      "category": "${topicTitle}"
    }
  ]
}`;

  const textResponse = await callGeminiApi({
    apiKey,
    model: chosenModel,
    prompt: notesText ? `${prompt}\n\nStudy Notes:\n${notesText.slice(0, 5000)}` : prompt,
    fileItem,
    systemInstruction: 'You are a master PRC Board of Architecture licensure exam writer specializing in PD 1096 (NBCP), BP 344, RA 9514, and Philippine architectural history.',
  });

  const jsonMatch = textResponse.match(/\{[\s\S]*\}/);
  if (!jsonMatch) {
    throw new Error('Failed to parse quiz JSON from Gemini response.');
  }

  const parsed = JSON.parse(jsonMatch[0]);
  return {
    questions: parsed.questions || [],
    flashcards: parsed.flashcards || [],
  };
}
